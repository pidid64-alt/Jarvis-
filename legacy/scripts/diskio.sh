#!/bin/bash
# Проверка активности дисков
iostat -d -x 1 2 2>/dev/null | awk 'NR>3 && NF>0 && $1 !~ /^Device/ && $1 !~ /^$/ {
    if ($14 > 80) print "Диск " $1 " сильно загружен: " $14 " процентов.";
    else if ($14 > 50) print "Диск " $1 " умеренно загружен: " $14 " процентов.";
}' | head -3

# Если iostat не установлен или нет активности
if [ $? -ne 0 ] || [ -z "$(iostat -d -x 1 2 2>/dev/null | awk 'NR>3 && NF>0 && $1 !~ /^Device/ && $1 !~ /^$/ {print}')" ]; then
    echo "Диски работают в нормальном режиме."
fi
